-- Crash reports (build step 18). Only sent when the player agrees: either they switched on
-- "Send crash reports" in Settings, or they pressed "Send to Nexus support" on one report.

create table crash_reports (
    id           bigint generated by default as identity primary key,
    player_uuid  uuid,                       -- empty if they weren't signed in to Nexus
    app_version  varchar(32),
    report       text not null,
    created_at   timestamp with time zone not null
);
create index crash_reports_created on crash_reports (created_at);
