-- The first Nexus database tables. Flyway runs this once, automatically, when the backend starts.
-- To change tables later, add a NEW file (V2__something.sql) – never edit this one after release.
-- Written to work on both PostgreSQL (the real server) and H2 (development).

-- Everyone who has signed in to Nexus (their Minecraft UUID and name).
create table players (
    uuid              uuid primary key,
    name              varchar(16)  not null,
    role              varchar(16)  not null default 'PLAYER',   -- PLAYER, MODERATOR, ADMIN
    show_server       boolean      not null default true,        -- friends can see which server I'm on
    dm_policy         varchar(16)  not null default 'FRIENDS',   -- FRIENDS, NOBODY
    playtime_minutes  bigint       not null default 0,
    favourite_server  varchar(255),
    banned_until      timestamp with time zone,
    ban_reason        varchar(255),
    muted_until       timestamp with time zone,
    created_at        timestamp with time zone not null,
    last_seen         timestamp with time zone not null
);
create index players_name on players (name);

-- Sign-ins. Only a fingerprint (SHA-256) of each token is stored, never the token itself.
create table sessions (
    token_hash   varchar(64) primary key,
    player_uuid  uuid not null references players (uuid) on delete cascade,
    created_at   timestamp with time zone not null,
    expires_at   timestamp with time zone not null
);

create table friend_requests (
    id          bigint generated by default as identity primary key,
    from_uuid   uuid not null references players (uuid) on delete cascade,
    to_uuid     uuid not null references players (uuid) on delete cascade,
    created_at  timestamp with time zone not null,
    unique (from_uuid, to_uuid)
);

-- Each friendship is stored twice (A→B and B→A), which keeps "list my friends" simple.
create table friendships (
    player_uuid  uuid not null references players (uuid) on delete cascade,
    friend_uuid  uuid not null references players (uuid) on delete cascade,
    since        timestamp with time zone not null,
    primary key (player_uuid, friend_uuid)
);

create table blocks (
    blocker_uuid  uuid not null references players (uuid) on delete cascade,
    blocked_uuid  uuid not null references players (uuid) on delete cascade,
    created_at    timestamp with time zone not null,
    primary key (blocker_uuid, blocked_uuid)
);

create table direct_messages (
    id         bigint generated by default as identity primary key,
    from_uuid  uuid not null references players (uuid) on delete cascade,
    to_uuid    uuid not null references players (uuid) on delete cascade,
    text       varchar(500) not null,
    sent_at    timestamp with time zone not null,
    read_at    timestamp with time zone
);
create index direct_messages_to on direct_messages (to_uuid, sent_at);

-- Short codes for sharing an instance setup, HUD layout or crosshair.
create table share_codes (
    code        varchar(16) primary key,
    kind        varchar(16) not null,          -- SETUP, HUD, CROSSHAIR
    data        text not null,
    owner_uuid  uuid not null references players (uuid) on delete cascade,
    created_at  timestamp with time zone not null
);
create index share_codes_owner on share_codes (owner_uuid, created_at);

create table reports (
    id            bigint generated by default as identity primary key,
    reporter_uuid uuid not null references players (uuid) on delete cascade,
    target_uuid   uuid not null references players (uuid) on delete cascade,
    reason        varchar(32)  not null,        -- CHAT, NAME, SKIN, CHEATING, OTHER
    details       varchar(1000),
    evidence      text,                         -- e.g. the reported messages
    status        varchar(16)  not null default 'OPEN',   -- OPEN, CLOSED
    handled_by    uuid,
    handled_at    timestamp with time zone,
    created_at    timestamp with time zone not null
);
create index reports_status on reports (status, created_at);
