-- Clans, honor, AFK-checked activity, honor events, clan chat and clan polls (build step 14).

create table clans (
    id           bigint generated by default as identity primary key,
    name         varchar(24)  not null,
    tag          varchar(5)   not null,
    description  varchar(300),
    owner_uuid   uuid not null references players (uuid),
    honor        bigint not null default 0,
    mvp          boolean not null default false,       -- the Nexus owner's clan ("Nexus MVP")
    created_at   timestamp with time zone not null
);
-- Names are also checked without caring about capitals in ClanService; tags are always stored in capitals.
create unique index clans_name on clans (name);
create unique index clans_tag on clans (tag);
create index clans_honor on clans (honor);

create table clan_members (
    clan_id      bigint not null references clans (id) on delete cascade,
    player_uuid  uuid   not null references players (uuid) on delete cascade,
    rank         varchar(16) not null,                 -- OWNER, CO_OWNER, FIRST_CLASS, VIP, MEMBER
    honor        bigint not null default 0,            -- honor this member earned for the clan
    joined_at    timestamp with time zone not null,
    primary key (clan_id, player_uuid)
);
create index clan_members_player on clan_members (player_uuid);

create table clan_invites (
    clan_id      bigint not null references clans (id) on delete cascade,
    player_uuid  uuid   not null references players (uuid) on delete cascade,
    invited_by   uuid   not null,
    created_at   timestamp with time zone not null,
    primary key (clan_id, player_uuid)
);

create table clan_messages (
    id         bigint generated by default as identity primary key,
    clan_id    bigint not null references clans (id) on delete cascade,
    from_uuid  uuid   not null references players (uuid) on delete cascade,
    text       varchar(256) not null,
    sent_at    timestamp with time zone not null
);
create index clan_messages_clan on clan_messages (clan_id, id);

create table clan_polls (
    id          bigint generated by default as identity primary key,
    clan_id     bigint not null references clans (id) on delete cascade,
    question    varchar(200) not null,
    options     varchar(400) not null,                -- options separated by a line break
    created_by  uuid not null,
    ends_at     timestamp with time zone not null,
    created_at  timestamp with time zone not null
);

create table clan_votes (
    poll_id      bigint not null references clan_polls (id) on delete cascade,
    player_uuid  uuid   not null references players (uuid) on delete cascade,
    choice       int    not null,
    primary key (poll_id, player_uuid)
);

-- One row per player per day: minutes judged active/AFK and the honor they earned or lost.
create table activity_days (
    player_uuid     uuid not null references players (uuid) on delete cascade,
    activity_date   date not null,          -- "day" is a reserved word in some databases
    active_minutes  int  not null default 0,
    counted_minutes int  not null default 0,          -- active minutes within the daily limit
    afk_minutes     int  not null default 0,
    honor           bigint not null default 0,
    last_report_at  timestamp with time zone,
    primary key (player_uuid, activity_date)
);

-- Honor events hosted by the Nexus owner (honor x multiplier between the start and end time).
create table honor_events (
    id          bigint generated by default as identity primary key,
    name        varchar(64) not null,
    multiplier  double precision not null,
    starts_at   timestamp with time zone not null,
    ends_at     timestamp with time zone not null,
    created_at  timestamp with time zone not null
);

-- Which clan a player's honor goes to (someone who owns two clans picks one), and Nexus Premium.
alter table players add column primary_clan_id bigint;
alter table players add column premium_until timestamp with time zone;
