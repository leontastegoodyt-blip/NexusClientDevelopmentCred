-- Nexus Partner Servers (build step 15): featured in the launcher; each can switch off Nexus mods it
-- doesn't allow (the in-game mod obeys, like the server-safe system from step 11).

create table partner_servers (
    id            bigint generated by default as identity primary key,
    name          varchar(48)  not null,
    address       varchar(255) not null,
    description   varchar(300),
    blocked_mods  varchar(1000) not null default '',   -- Nexus mod ids, separated by commas ("*blockable" allowed)
    manager_uuid  uuid,                                -- the server's own staff member who may edit the rules
    sort_order    int not null default 0,
    created_at    timestamp with time zone not null
);
create unique index partner_servers_address on partner_servers (address);
