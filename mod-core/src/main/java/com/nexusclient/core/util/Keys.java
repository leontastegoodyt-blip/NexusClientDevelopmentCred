package com.nexusclient.core.util;

/**
 * Keys – the keyboard keys the Nexus menus care about, using the key numbers of GLFW (the library
 * Minecraft 1.13+ uses for input). The 1.8.9 mod translates its older key numbers into these.
 */
public final class Keys {

    public static final int ESCAPE = 256;
    public static final int ENTER = 257;
    public static final int TAB = 258;
    public static final int BACKSPACE = 259;
    public static final int DELETE = 261;
    public static final int RIGHT = 262;
    public static final int LEFT = 263;
    public static final int DOWN = 264;
    public static final int UP = 265;
    public static final int RIGHT_SHIFT = 344;
    public static final int LEFT_CONTROL = 341;
    public static final int V = 86;
    public static final int C = 67;

    private Keys() {}
}
