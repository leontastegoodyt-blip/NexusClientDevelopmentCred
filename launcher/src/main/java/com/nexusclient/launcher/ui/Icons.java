    /**
     * Makes an icon node that can be put in a button or layout.
     *
     * @param path one of the icon shapes above
     * @param size how big the icon should be, in pixels
     */
    public static Node create(String path, double size) {
        SVGPath shape = new SVGPath();
        shape.setContent(path);
        shape.getStyleClass().add("icon"); // lets theme.css colour it

        // The shapes are drawn on a 24 x 24 grid, so scale them to the size we want.
        double scale = size / 24.0;
        shape.setScaleX(scale);
        shape.setScaleY(scale);

        // Put the shape in a fixed-size box so every icon takes up exactly size x size pixels.
        StackPane box = new StackPane(shape);
        box.setMinSize(size, size);
        box.setPrefSize(size, size);
        box.setMaxSize(size, size);
        return box;
    }
